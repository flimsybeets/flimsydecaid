// Builds the generic (brand-neutral) Guide me scenes into
// src/features/guide/genericScenes.ts. Everything is modelled in millimetres
// and projected orthographically (geo.cjs). Static SVG only: animation lives
// in src/features/guide/genericArt.css, keyed on the k-* classes emitted here.
//   node scripts/generic-art/build.cjs            (then, after changing a scene:)
//   node scripts/generic-art/measure.cjs && node scripts/generic-art/build.cjs
const fs = require('fs');
const path = require('path');
const { Style } = require('./style.cjs');
const { minifySvg } = require('./minify.cjs');
const scenes = require('./scenes.cjs');

const W = 448, H = 320;
const ORDER = ['weigh', 'spray', 'grinder', 'grind', 'wdt', 'distribute', 'funnel', 'basket', 'tamp', 'puckscreen', 'paper', 'minerals', 'pull', 'knock', 'rinse', 'steam', 'done'];
let frames = {};
try { frames = JSON.parse(fs.readFileSync(path.join(__dirname, 'frames.json'), 'utf8')); } catch { /* first run */ }
// viewBox = the measured bounding box padded to the panel's aspect
function fit(box, pad = 0.06, extra = {}) {
  if (!box) return `0 0 ${W} ${H}`;
  let [x, y, w, h] = box;
  const t = extra.top ?? 0, b = extra.bottom ?? 0;
  y -= t; h += t + b;
  const p = Math.max(w, h) * pad;
  x -= p; y -= p; w += 2 * p; h += 2 * p;
  const asp = W / H;
  if (w / h > asp) { const nh = w / asp; y -= (nh - h) / 2; h = nh; } else { const nw = h * asp; x -= (nw - w) / 2; w = nw; }
  return [x, y, w, h].map((v) => +v.toFixed(1)).join(' ');
}
const res = {};
let COMMON = '';
ORDER.forEach((k, i) => {
  if (!scenes[k]) return;
  const S = Style(`n${i.toString(36)}`, 400);
  const meta = scenes[k](S) || {};
  const svg = minifySvg(`<defs>${S.defs.join('')}</defs>${S.out.join('')}`);
  COMMON = minifySvg(S.common.join(''));
  const { pad, extra, vb, ...rest } = meta;
  res[k] = { vb: vb || fit(frames[k], pad, extra), svg, ...rest };
});
const ts = `// Generated by scripts/generic-art/build.cjs. Do not edit by hand.

export interface GuideScene {
  vb: string;
  /** Static SVG markup; '<!--@-->' marks where the live parts go. */
  svg: string;
  /** Plane transform + position of the scale's display (live weight). */
  lcd?: string;
  lcdAt?: [number, number];
  /** Where the grind setting readout sits. */
  num?: [number, number];
}

/** The root svg gets \`set-generic\`, which scopes genericArt.css. */
export const id = 'generic';

/** Gradients shared by every scene (render once per svg, in <defs>). */
export const COMMON_DEFS = \`${COMMON}\`;

export const SCENES: Record<string, GuideScene> = {
${Object.entries(res).map(([k, v]) => `  ${k}: { ${Object.entries(v).map(([n, x]) => `${n}: ${n === 'svg' ? '`' + x + '`' : JSON.stringify(x)}`).join(', ')} },`).join('\n')}
};
`;
fs.writeFileSync(path.join(__dirname, '../../src/features/guide/genericScenes.ts'), ts);
console.log(Object.entries(res).map(([k, v]) => `${k} ${(v.svg.length / 1024).toFixed(1)}k`).join('  '), ' total', (ts.length / 1024).toFixed(1) + 'k');
